// Builds the procedural pickleball player: mesh + skeleton + skin + animations -> GLB.
//   node tools/avatar/build.mjs [--parts]  -> assets/3d/pickleball_player.glb (+ viewer, + app module)
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MATERIALS } from './lib/body.mjs';
import { buildParts } from './lib/character.mjs';
import { bakeClips } from './lib/anim.mjs';
import { buildGLB } from './lib/gltf.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, '../../assets/3d');
mkdirSync(outDir, { recursive: true });

const parts = buildParts();
const clips = bakeClips();
const { glb, stats } = buildGLB({ parts, materials: MATERIALS, clips });

const glbPath = join(outDir, 'pickleball_player.glb');
writeFileSync(glbPath, glb);

// Self-contained viewer (GLB embedded) so it opens straight from disk.
const tpl = readFileSync(join(here, 'viewer.template.html'), 'utf8');
writeFileSync(join(outDir, 'pickleball_player_viewer.html'), tpl.replace('__GLB_BASE64__', glb.toString('base64')));

// The app embeds the model as base64 (Android release builds can't fetch bundled .glb assets by URL).
const appModule = resolve(here, '../../src/game/player3dModel.ts');
writeFileSync(appModule, [
  '// GENERATED by tools/avatar/build.mjs: the 3D player (GLB), base64. Do not edit by hand.',
  '/* eslint-disable */',
  `export const PLAYER_GLB_BASE64 =\n  '${glb.toString('base64')}';`,
  '',
].join('\n'));

console.log(`wrote ${glbPath} (${(glb.length / 1024).toFixed(0)} KB)`);
console.log(`  ${stats.parts} parts, ${stats.vertices} vertices, ${stats.triangles} triangles, ${stats.materials} materials, ${stats.bones} bones`);
console.log(`  clips: ${clips.map(c => `${c.name} ${c.times[c.times.length - 1].toFixed(2)}s${c.loop ? ' loop' : ''}`).join(', ')}`);
if (process.argv.includes('--parts')) for (const p of parts) console.log(`  ${p.name.padEnd(22)} ${p.mb.pos.length}`);
